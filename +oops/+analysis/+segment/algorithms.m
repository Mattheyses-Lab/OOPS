function definitions = algorithms(id)
%ALGORITHMS Return typed definitions for supported segmentation algorithms.
arguments
    id (1,1) string = ""
end

definitions = [punctaDefinition();filamentDefinition()];

if id ~= ""
    definitions = definitions([definitions.ID] == id);
    if isempty(definitions)
        error('oops:analysis:UnknownAlgorithm', ...
            'Unsupported segmentation algorithm: %s',id);
    end
end
end

function definition = punctaDefinition()
%PUNCTADEFINITION Describe compact-object enhancement and thresholding.
threshold = oops.analysis.ParameterDefinition( ...
    Name="Threshold", ...
    Label="Threshold", ...
    Default=[], ...
    Limits=[0 1], ...
    Adjustable=true);

definition = oops.analysis.segment.Algorithm( ...
    ID="Puncta/1", ...
    Label="Puncta", ...
    Description="Enhances compact bright objects and applies an automatic or manual threshold.", ...
    RunFcn=@oops.analysis.segment.puncta, ...
    PreviewFcn=@(diagnostics,recipe) diagnostics.Enhanced > recipe.Values.Threshold, ...
    ParameterDefinitions=threshold);
end

function definition = filamentDefinition()
%FILAMENTDEFINITION Describe elongated-object segmentation.
definition = oops.analysis.segment.Algorithm( ...
    ID="Filaments/1", ...
    Label="Filaments", ...
    Description="Detects elongated filament-like foreground objects.", ...
    RunFcn=@oops.analysis.segment.filaments);
end
