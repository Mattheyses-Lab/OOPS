function T = projectSummaryTable(project)
%PROJECTSUMMARYTABLE Build one-row project identity and count summary.
groups = project.Groups;
imageCount = sum(arrayfun(@(group) numel(group.Images),groups));
objectCount = 0; auxiliaryCount = 0;
for group = reshape(groups,1,[])
    objectCount = objectCount+sum(arrayfun(@(image) numel(image.Objects),group.Images));
    auxiliaryCount = auxiliaryCount+sum(arrayfun( ...
        @(image) numel(image.AuxiliaryChannels),group.Images));
end
T = table(project.Name,project.ID,project.Version,project.SchemaVersion, ...
    string(project.SourcePath),numel(groups),imageCount,objectCount, ...
    numel(project.Calibrations),numel(project.Channels.Channels), ...
    numel(project.Labels.labels()),auxiliaryCount, ...
    'VariableNames',{'Project name','Project ID','OOPS version','Project schema', ...
    'Project file','Group count','Image count','Object count', ...
    'Calibration count','Channel count','Label count','Auxiliary assignment count'});
end
